import { useState } from 'react';
import JSZip from 'jszip';

export const useDeploy = (
  currentProject: any,
  currentFiles: any,
  updateProjectCode: any,
  addLog: any,
  trackEvent: any,
  selectedModel: string,
  deployTokens: any,
  githubRepo: string,
  surgeDomain: string,
  handleAIError: any
) => {
  const [deployLoading, setDeployLoading] = useState(false);
  const [deployProgress, setDeployProgress] = useState(0);
  const [deployResult, setDeployResult] = useState<{ url: string; service: string } | null>(null);
  const [qrCodeUrl, setQrCodeUrl] = useState<string | null>(null);

  const generateQRCode = (url: string) => {
    const qrUrl = `https://api.qrserver.com/v1/create-qr-code/?size=300x300&data=${encodeURIComponent(url)}`;
    setQrCodeUrl(qrUrl);
  };

  const handleZipExport = async () => {
    if (!currentProject) return;
    addLog("SYSTEM: Compiling artifacts into ZIP archive...");
    const zip = new JSZip();
    
    const files = { ...currentFiles };
    
    if (!files['README.md']) {
      files['README.md'] = `# ${currentProject.name?.toUpperCase() || 'UNTITLED PROJECT'}
Generated by WebForge OS.

## 🚀 Getting Started
1. Extract the contents.
2. Open \`index.html\` in your browser or run a local server.

## 🛠️ Project Type: ${currentProject.type?.toUpperCase() || 'WEB'}
Engineered with First Principles.`;
    }

    if (!files['.env.example'] && ['saas', 'ecommerce', 'node', 'fastapi'].includes(currentProject.type || '')) {
      files['.env.example'] = `# Forge Environment Configuration
VITE_API_URL=http://localhost:3000
# Add your specific integration keys here`;
    }

    Object.entries(files).forEach(([path, content]) => {
      zip.file(path, content as string);
    });

    const blob = await zip.generateAsync({ type: 'blob' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${currentProject.name.toLowerCase().replace(/\s+/g, '-')}_v${currentProject.currentVersionIndex + 1}.zip`;
    link.click();
    trackEvent('export_zip', { projectId: currentProject.id, files: Object.keys(files).length });
    addLog("SYSTEM: Export successful.");
  };

  const handleDeploy = async (service: 'netlify' | 'github' | 'surge') => {
    setDeployLoading(true);
    setDeployProgress(10);
    setDeployResult(null);

    try {
      let endpoint = '';
      let body: any = { files: currentFiles };

      if (service === 'netlify') {
        endpoint = '/api/deploy/netlify';
        body.token = deployTokens.netlify;
      } else if (service === 'github') {
        endpoint = '/api/deploy/github';
        body.token = deployTokens.github;
        body.repoName = githubRepo || currentProject?.name?.toLowerCase().replace(/\s+/g, '-') || 'webforge-project';
      } else if (service === 'surge') {
        endpoint = '/api/deploy/surge';
        body.token = deployTokens.surge;
        body.domain = surgeDomain || `${currentProject?.name?.toLowerCase().replace(/\s+/g, '-') || 'webforge'}.surge.sh`;
      }

      setDeployProgress(40);
      const res = await fetch(endpoint, {
        method: 'POST',
        headers: { 
          'Content-Type': 'application/json',
          'x-model': selectedModel
        },
        body: JSON.stringify(body)
      });

      setDeployProgress(80);
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || "Deployment failed");

      setDeployResult({ url: data.url, service });
      setDeployProgress(100);
      trackEvent('deploy_success', { service, url: data.url });
      generateQRCode(data.url);
    } catch (err: any) {
      handleAIError(err);
      trackEvent('deploy_error', { service, error: err.message });
    } finally {
      setTimeout(() => {
        setDeployLoading(false);
        setDeployProgress(0);
      }, 500);
    }
  };

  return {
    deployLoading,
    deployProgress,
    deployResult,
    qrCodeUrl,
    setQrCodeUrl,
    handleDeploy,
    handleZipExport,
    generateQRCode,
    setDeployLoading
  };
};
